"""Generate runtime/src/kexports.h from runtime/kernel/xboxkrnl.exe.def.

Usage: python -I tools/gen_kexports.py
"""
import os
import re

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
rows = {}
for line in open(os.path.join(ROOT, "runtime", "kernel", "xboxkrnl.exe.def")):
    m = re.match(r"\s+(@?)(\w+)(?:@(\d+))?\s+@\s*(\d+)\s+NONAME(\s+DATA)?", line)
    if not m:
        continue
    fast, name, argb, ordinal, data = m.groups()
    conv = "KC_DATA" if data else "KC_FASTCALL" if fast else "KC_CDECL" if argb is None else "KC_STDCALL"
    rows[int(ordinal)] = (name, conv, int(argb or 0))
with open(os.path.join(ROOT, "runtime", "src", "kexports.h"), "w") as o:
    o.write("/* Generated by tools/gen_kexports.py from xboxkrnl.exe.def (CC0). */\n#pragma once\n")
    o.write("enum { KC_NONE, KC_STDCALL, KC_FASTCALL, KC_CDECL, KC_DATA };\n")
    o.write("typedef struct { const char *name; int conv; int argbytes; } KExport;\n")
    o.write("static const KExport k_exports[379] = {\n")
    for i in range(379):
        if i in rows:
            n, cv, a = rows[i]
            o.write(f'    [{i}] = {{"{n}", {cv}, {a}}},\n')
    o.write("};\n")
print(len(rows), "exports")
