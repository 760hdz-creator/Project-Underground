"""Compile runtime/shaders/*.vert|*.frag to SPIR-V and write runtime/src/shaders_spv.h (committed).

Dev-only: needs glslang from `python -I tools/bootstrap.py --dev`. Player builds use the committed header.
Usage: python -I tools/shaders.py
"""
import os
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import bootstrap  # noqa: E402

SRC = os.path.join(ROOT, "runtime", "shaders")
OUT = os.path.join(ROOT, "runtime", "src", "shaders_spv.h")


def main():
    glslang = os.path.join(bootstrap.glslang_dir(), "bin", "glslang.exe" if os.name == "nt" else "glslang")
    if not os.path.exists(glslang):
        sys.exit("ERROR: glslang missing: run python -I tools/bootstrap.py --dev")
    parts = ["/* Generated by tools/shaders.py from runtime/shaders: SPIR-V for the Vulkan renderer. Do not edit. */",
             "#pragma once", "#include <stdint.h>", ""]
    for name in sorted(os.listdir(SRC)):
        if not name.endswith((".vert", ".frag")):
            continue
        with tempfile.TemporaryDirectory() as td:
            spv = os.path.join(td, "out.spv")
            p = subprocess.run([glslang, "-V", "--target-env", "vulkan1.3", "-Os", "-o", spv, os.path.join(SRC, name)],
                               stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
            if p.returncode:
                sys.exit(f"ERROR: {name}\n{p.stdout}")
            data = open(spv, "rb").read()
        ident = "spv_" + name.replace(".", "_")
        words = [int.from_bytes(data[i:i + 4], "little") for i in range(0, len(data), 4)]
        parts.append(f"static const uint32_t {ident}[{len(words)}] = {{")
        for i in range(0, len(words), 8):
            parts.append("    " + ", ".join(f"0x{w:08X}u" for w in words[i:i + 8]) + ",")
        parts.append("};")
        parts.append("")
        print(f"{name}: {len(data)} bytes")
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(parts))
    print("wrote " + os.path.relpath(OUT, ROOT))


if __name__ == "__main__":
    main()
